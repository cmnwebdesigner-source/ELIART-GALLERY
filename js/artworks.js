function createInfoBadge(text) {
    const span = document.createElement('span');
    span.className = 'bg-white border border-beige/70 px-3 py-1 rounded-full';
    span.textContent = text;
    return span;
}

function setModalImage(src, alt) {
    const modalImage = document.getElementById('artwork-modal-image');
    if (!modalImage) return;

    const wrapper = modalImage.parentElement;
    if (wrapper) {
        wrapper.classList.remove('image-missing-box');
        wrapper.querySelectorAll('.image-missing-message').forEach(message => message.remove());
    }

    modalImage.dataset.fallbackApplied = 'false';
    modalImage.style.opacity = '1';
    modalImage.onerror = () => {
        if (typeof handleMissingImage === 'function') {
            handleMissingImage(modalImage);
        }
    };

    modalImage.src = src;
    modalImage.alt = alt;

    document.querySelectorAll('.artwork-thumb').forEach(thumb => {
        thumb.classList.toggle('active-thumb', thumb.dataset.src === src);
    });
}

function openArtwork(index, keepOpen = false) {
    const artwork = artworks[index];
    const modal = document.getElementById('artwork-modal');
    const title = document.getElementById('artwork-modal-title');
    const info = document.getElementById('artwork-modal-info');
    const desc = document.getElementById('artwork-modal-desc');
    const thumbs = document.getElementById('artwork-modal-thumbs');

    if (!artwork || !modal || !title || !info || !desc || !thumbs) return;

    activeArtworkIndex = index;
    const artworkTitle = localValue(artwork.title);
    title.textContent = artworkTitle;

    info.innerHTML = '';
    [artwork.price, ...localArray(artwork.info)].forEach(item => {
        if (item) info.appendChild(createInfoBadge(item));
    });

    desc.innerHTML = '';
    localArray(artwork.description).forEach(paragraph => {
        const p = document.createElement('p');
        p.textContent = paragraph;
        desc.appendChild(p);
    });

    thumbs.innerHTML = '';
    artwork.images.forEach((imageSrc, imageIndex) => {
        const button = document.createElement('button');
        button.type = 'button';
        button.className = 'artwork-thumb';
        button.dataset.src = imageSrc;
        button.setAttribute('aria-label', `${artworkTitle} imagine ${imageIndex + 1}`);
        button.onclick = () => setModalImage(imageSrc, artworkTitle);

        const img = document.createElement('img');
        img.src = imageSrc;
        img.alt = `${artworkTitle} imagine ${imageIndex + 1}`;
        button.appendChild(img);
        thumbs.appendChild(button);
    });

    setModalImage(artwork.images[0], artworkTitle);
    modal.classList.remove('hidden');
    document.body.style.overflow = 'hidden';
}

function closeArtworkModal() {
    const modal = document.getElementById('artwork-modal');
    if (!modal) return;

    modal.classList.add('hidden');
    activeArtworkIndex = null;
    document.body.style.overflow = '';
}

document.addEventListener('keydown', (event) => {
    if (event.key === 'Escape') {
        closeArtworkModal();
    }
});

