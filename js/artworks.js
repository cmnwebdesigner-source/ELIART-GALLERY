const reverseStaticTranslations = Object.fromEntries(
    Object.entries(staticTranslations).map(([ro, en]) => [en, ro])
);

function localValue(value) {
    if (!value) return '';
    if (typeof value === 'string') return value;
    return value[currentLanguage] || value.ro || value.en || '';
}

function localArray(value) {
    if (!value) return [];
    if (Array.isArray(value)) return value;
    return value[currentLanguage] || value.ro || value.en || [];
}

function preserveSpacing(original, replacement) {
    const leading = original.match(/^\s*/)[0];
    const trailing = original.match(/\s*$/)[0];
    return `${leading}${replacement}${trailing}`;
}

function translateLooseTextNodes() {
    const map = currentLanguage === 'en' ? staticTranslations : reverseStaticTranslations;
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT,
        {
            acceptNode(node) {
                const parent = node.parentElement;
                if (!parent) return NodeFilter.FILTER_REJECT;
                if (['SCRIPT', 'STYLE', 'NOSCRIPT'].includes(parent.tagName)) return NodeFilter.FILTER_REJECT;
                const text = node.nodeValue;
                if (!text || !text.trim()) return NodeFilter.FILTER_REJECT;
                return NodeFilter.FILTER_ACCEPT;
            }
        }
    );

    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);

    nodes.forEach(node => {
        const trimmed = node.nodeValue.trim().replace(/\s+/g, ' ');
        if (Object.prototype.hasOwnProperty.call(map, trimmed)) {
            node.nodeValue = preserveSpacing(node.nodeValue, map[trimmed]);
        }
    });
}

function syncLanguageSwitches() {
    document.body.classList.toggle('lang-en', currentLanguage === 'en');
    document.body.classList.toggle('lang-ro', currentLanguage === 'ro');

    document.querySelectorAll('.language-toggle').forEach(button => {
        button.setAttribute('aria-label', currentLanguage === 'ro' ? 'Switch to English' : 'Switch to Romanian');
        button.setAttribute('aria-pressed', currentLanguage === 'en' ? 'true' : 'false');
        button.dataset.currentLanguage = currentLanguage;
    });
}

function applyLanguageToStaticContent() {
    document.documentElement.lang = currentLanguage;
    document.title = currentLanguage === 'en'
        ? 'ELIART_2020 | Contemporary Art by Biró Melinda'
        : 'ELIART_2020 | Artă Contemporană de Biró Melinda';

    document.querySelectorAll('[data-ro][data-en]').forEach(element => {
        const value = element.getAttribute(`data-${currentLanguage}`);
        if (typeof value === 'string') {
            element.innerHTML = value;
        }
    });

    translateLooseTextNodes();
    syncLanguageSwitches();

    document.querySelectorAll('.js-back-label').forEach(element => {
        element.textContent = uiText[currentLanguage].back;
    });

    const modalContactButton = document.querySelector('#artwork-modal button[onclick*="navigateTo(\'contact\')"]');
    if (modalContactButton) {
        modalContactButton.textContent = uiText[currentLanguage].contactArtwork;
    }
}

function initLanguage() {
    applyLanguageToStaticContent();
}

function toggleLanguage() {
    currentLanguage = currentLanguage === 'ro' ? 'en' : 'ro';
    localStorage.setItem('eliart-language', currentLanguage);
    applyLanguageToStaticContent();
    renderArtworkCards();

    if (activeArtworkIndex !== null) {
        openArtwork(activeArtworkIndex, true);
    }
}

function escapeHtml(text) {
    return String(text || '').replace(/[&<>"']/g, char => ({
        '&': '&amp;',
        '<': '&lt;',
        '>': '&gt;',
        '"': '&quot;',
        "'": '&#039;'
    }[char]));
}

